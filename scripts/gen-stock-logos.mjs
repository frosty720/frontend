// Bundled logos for the Stocks page.
//
//   node scripts/gen-stock-logos.mjs    # rewrites public/stock-logos/ and src/config/stockLogos.ts
//
// Robinhood's API gives every stock token the same Robinhood icon, so the real company logos come
// from Financial Modeling Prep's public image endpoint, fetched once here and served from our site.
// Re-run when Arcus lists new stocks; until then a new one shows Robinhood's icon.
//
// FMP's PNGs mix styles: some carry their own background, some are white marks meant for dark UIs,
// some dark marks meant for light ones. Each is placed on a background picked from its own pixels so
// it stays visible in the app's dark theme (src/config/__tests__/stockLogos.test.ts checks every file).
import fs from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'

const ROUTER_TOKENS = 'https://router.spot.arcus.xyz/v1/tokens'
const FMP = (symbol) => `https://financialmodelingprep.com/image-stock/${symbol}.png`
const CATEGORIES = new Set(['stock', 'index', 'commodity'])
// FMP has no usable logo for these (checked by eye 2026-10-13); they keep Robinhood's icon.
//   FLY  - FMP shows Fly Leasing (the ticker's old owner); the token is Firefly Aerospace
//   TSEM - FMP shows a photo of a building instead of Tower Semiconductor's logo
//   SPCX - a tiny wordmark on a gradient in a 100px image: unreadable at any size
const SKIP = new Set(['FLY', 'TSEM', 'SPCX'])

const ROOT = path.join(path.dirname(new URL(import.meta.url).pathname), '..')
const OUT_DIR = path.join(ROOT, 'public', 'stock-logos')
const MANIFEST = path.join(ROOT, 'src', 'config', 'stockLogos.ts')

const SIZE = 96
const DARK = { r: 28, g: 28, b: 28 } // close to the app's surface colour
const WHITE = { r: 255, g: 255, b: 255 }
const luminance = (r, g, b) => 0.299 * r + 0.587 * g + 0.114 * b

/** Background and box for one logo, from its decoded RGBA pixels. */
function placement(data) {
	let opaque = 0
	let light = 0
	for (let i = 0; i < data.length; i += 4) {
		if (data[i + 3] <= 128) continue
		opaque++
		if (luminance(data[i], data[i + 1], data[i + 2]) > 220) light++
	}
	const pixels = data.length / 4
	// A logo with its own background: extend that colour (its top-left pixel) around it.
	if (opaque / pixels > 0.97) return { background: { r: data[0], g: data[1], b: data[2] }, box: 68 }
	// A mostly-white mark on transparency was drawn for dark backgrounds; anything else reads on white.
	return { background: opaque > 0 && light / opaque > 0.5 ? DARK : WHITE, box: 60 }
}

async function render(png) {
	const { data } = await sharp(png).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
	const { background, box } = placement(data)
	// Trim the logo's own empty border first (transparent or a flat colour), or a small wordmark in a
	// big square — SPCX — ends up unreadably small.
	const logo = await sharp(png).trim().resize(box, box, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } }).png().toBuffer()
	return sharp({ create: { width: SIZE, height: SIZE, channels: 3, background } })
		.composite([{ input: logo, gravity: 'center' }])
		.png({ compressionLevel: 9, palette: true })
		.toBuffer()
}

const tokens = await (await fetch(ROUTER_TOKENS)).json()
const stocks = tokens.filter((t) => t.chainId === 4663 && CATEGORIES.has(t.category) && !SKIP.has(t.symbol))

fs.rmSync(OUT_DIR, { recursive: true, force: true })
fs.mkdirSync(OUT_DIR, { recursive: true })

const written = []
for (const token of stocks) {
	const res = await fetch(FMP(token.symbol), { headers: { 'user-agent': 'Mozilla/5.0' } })
	if (!res.ok) {
		console.warn(`skip ${token.symbol}: FMP answered ${res.status}`)
		continue
	}
	const address = token.address.toLowerCase()
	fs.writeFileSync(path.join(OUT_DIR, `${address}.png`), await render(Buffer.from(await res.arrayBuffer())))
	written.push({ address, symbol: token.symbol })
	await new Promise((resolve) => setTimeout(resolve, 150)) // one request at a time, gently
}

written.sort((a, b) => a.symbol.localeCompare(b.symbol))
fs.writeFileSync(
	MANIFEST,
	`// GENERATED by scripts/gen-stock-logos.mjs — do not edit by hand.
//
// Stock tokens with a bundled logo at /stock-logos/<address>.png (lowercase address), keyed by
// address because a ticker can change hands while the token contract cannot.
export const STOCK_LOGO_ADDRESSES: ReadonlySet<string> = new Set([
${written.map(({ address, symbol }) => `\t'${address}', // ${symbol}`).join('\n')}
]);
`,
)
console.log(`wrote ${written.length} logos to public/stock-logos and src/config/stockLogos.ts`)
