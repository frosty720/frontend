// One-off: original purchase dates of the vaults migrated from 3888 to 3890.
//
//   node scripts/gen-migrated-vault-dates.mjs    # rewrites src/config/vaultMigratedPurchaseDates.ts
//
// migrateVaults() re-minted the 3888 snapshot on 3890 under the SAME token ids, so on 3890 every
// migrated vault looks bought on cutover day (2026-09-07). The real purchase time is the 3888 vault
// subgraph's createdAtTimestamp for that id. The migrated set is frozen (closeMigration() is one-way),
// so this list never changes and the app need not depend on the 3888 subgraph staying online.
//
// Which ids were migrated comes from the chain, not a date guess: VaultMigrated logs emitted by the
// 3890 VaultManager. Aborts unless every migrated id has a 3888 purchase time.
import fs from 'node:fs'
import path from 'node:path'
import { createPublicClient, http, parseAbiItem } from 'viem'

const RPC = process.env.KALYCHAIN_RPC_URL || 'https://mainrpc.kalychain.io/rpc'
const VAULT_MANAGER = '0xDA2A7a2D504949896e709F546B6Bc06C2E7c5982'
const SUBGRAPH_3890 = 'https://app.kalyswap.io/subgraphs/name/vault-subgraph-kmt'
const SUBGRAPH_3888 = 'https://app.kalyswap.io/subgraphs/name/vault-subgraph-kalychain-mainnet'
const OUT = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'src', 'config', 'vaultMigratedPurchaseDates.ts')
const VAULT_MIGRATED = parseAbiItem('event VaultMigrated(uint256 indexed tokenId, address indexed owner, uint8 tier)')

async function query(url, gql) {
	const res = await fetch(url, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ query: gql }) })
	const body = await res.json()
	if (body.errors) throw new Error(`${url}: ${JSON.stringify(body.errors)}`)
	return body.data
}

// The migration blocks: every 3890 vault minted in a tx that minted more than one (purchases mint one).
const { vaults } = await query(SUBGRAPH_3890, '{ vaults(first: 1000, orderBy: tokenId) { txHash createdAtBlock } }')
const perTx = new Map()
for (const vault of vaults) perTx.set(vault.txHash, [...(perTx.get(vault.txHash) ?? []), Number(vault.createdAtBlock)])
const blocks = [...perTx.values()].filter((list) => list.length > 1).flat()
const fromBlock = BigInt(Math.min(...blocks))
const toBlock = BigInt(Math.max(...blocks))

const client = createPublicClient({ transport: http(RPC) })
const logs = await client.getLogs({ address: VAULT_MANAGER, event: VAULT_MIGRATED, fromBlock, toBlock })
const ids = logs.map((log) => log.args.tokenId.toString())
if (ids.length === 0 || new Set(ids).size !== ids.length) throw new Error(`bad VaultMigrated set: ${ids.length} logs`)

const old = await query(SUBGRAPH_3888, `{ vaults(first: 1000, where: { tokenId_in: [${ids.join(',')}] }) { tokenId createdAtTimestamp } }`)
const purchasedAt = new Map(old.vaults.map((vault) => [vault.tokenId, Number(vault.createdAtTimestamp)]))
const missing = ids.filter((id) => !purchasedAt.has(id))
if (missing.length > 0) throw new Error(`no 3888 purchase time for ids ${missing.join(', ')}`)

const sorted = ids.map(Number).sort((a, b) => a - b)
const lines = sorted.map((id) => `\t${id}: ${purchasedAt.get(String(id))},`).join('\n')
fs.writeFileSync(
	OUT,
	`// GENERATED by scripts/gen-migrated-vault-dates.mjs — do not edit by hand.
//
// Unix-second purchase times of the ${sorted.length} vaults migrated from 3888 (VaultMigrated logs on the
// 3890 VaultManager, blocks ${fromBlock}–${toBlock}), read from the 3888 vault subgraph. On 3890 these
// vaults were minted on cutover day; this is when they were actually bought. Frozen: migration is closed.
export const MIGRATED_VAULT_PURCHASED_AT: Readonly<Record<number, number>> = {
${lines}
};
`,
)
console.log(`wrote ${sorted.length} migrated vault purchase dates to ${path.relative(process.cwd(), OUT)}`)
